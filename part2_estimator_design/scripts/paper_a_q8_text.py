NO_FREE = {"oracle start": ["M1 seq (no elimination)", "M2 independent, marginal rule", "M2 independent, pairwise rule"],
           "sign-aware": ["M1 seq safe (oracle start)", "M2 safe (oracle start)"]}
STATIC = "M1 static (exact gap, exact variances)"
POOL_NAME = {"uccsd": "UCCSD", "qeb": "QEB", "qubit": "qubit-ADAPT", "gsd_qeb": "generalized QEB", "gsd_qubit": "generalized qubit",
             "ceo": "OVP-CEO"}
QUBIT_POOLS, EXCITATION_POOLS = ("qubit", "gsd_qubit"), ("uccsd", "qeb", "gsd_qeb")
STATE_OF_POOL_CASE = {"CISD": "CISD", "HF": "Hartree--Fock"}
BASELINE_NAME = {"M1 seq (no elimination)": "the sequential M1", "M2 independent, marginal rule": "independent BAI",
                 "M2 independent, pairwise rule": "independent BAI"}
H2O_LABEL = {"H2O_eq_CISD": "equilibrium CISD", "H2O_stretch_CISD": "stretched CISD", "H2O_eq_ADAPT11": r"equilibrium ADAPT$_{11}$",
             "H2O_stretch_ADAPT8": r"stretched ADAPT$_8$"}
GOOD = 0.95
NUMBER = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten", 11: "eleven", 12: "twelve"}
# TYPED: no stored file holds these (see the module docstring); LiH_CREDIT_FALLBACK is used only if the step-5 meta lacks credit_shots.
