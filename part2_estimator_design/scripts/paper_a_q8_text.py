CASES = ["H4_square_eq_side1p0_CISD", "H4_square_stretch_side2p0_CISD", "LiH_R3p0_HF", "LiH_R3p0_ADAPT3", "LiH_R3p0_ADAPT5",
         "H2O_eq_CISD", "H2O_stretch_CISD", "H2O_eq_ADAPT11", "H2O_stretch_ADAPT8"]
H4, LIH_CASES, H2O = CASES[0:2], CASES[2:5], CASES[5:9]
