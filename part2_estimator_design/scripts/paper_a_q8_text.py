#!/usr/bin/env python3
"""Write the prose of Paper A's Q8 subsection from the stored results (every number is computed here).

The tables are generated by ``paper_a_sota_latex.py``; this script writes the text around them and splices
the whole subsection into the paper between ``\\subsection{Q8`` and the Results scaffold comment (or, once the
scaffold is gone, ``\\section{Discussion}``), keeping the generated-table block that is already there.  The text is a
set of templates whose ``@slot@`` entries are filled with numbers from ``runs/paper_a/*.csv``, ``reuse_overlap.csv``,
``cost_summary.csv``, the step-3 planning bounds, the step-5 meta files (``credit_shots``), the step-7 trial files
and ``step6_pool_census.csv``.  The claims of the text that a number can contradict are checked (``CHECKS``); a failed
check is printed as a warning and means that the sentence must be re-read.  Run order after new results arrive::

    bash cluster/sync_from_trillium.sh USER python
    python scripts/paper_a_sota_tables.py
    python scripts/paper_a_sota_latex.py --splice ../reports/draft.tex
    python scripts/paper_a_q8_text.py --paper ../reports/draft.tex

Numbers with no stored source (typed below, marked ``TYPED``): the per-shot variance of the leading gradient of H4 (66), the
IC run without the anytime correction (69% of 100 trials with a missed interval, 3 best candidates eliminated, a factor 2.3
in the median), and the LiH credit of the energy data when the step-5 meta of the merged LiH run lacks it.
"""
